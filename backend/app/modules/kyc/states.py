from app.common.enums import CaseStatus as S

TRANSITIONS: dict[S, frozenset[S]] = {
    S.CREATED: frozenset({S.IN_PROGRESS, S.PROCESSING, S.ACTION_REQUIRED, S.EXPIRED}),
    S.IN_PROGRESS: frozenset({S.PROCESSING, S.ACTION_REQUIRED, S.MANUAL_REVIEW, S.VERIFIED, S.NOT_VERIFIED, S.FAILED, S.EXPIRED}),
    S.ACTION_REQUIRED: frozenset({S.IN_PROGRESS, S.PROCESSING, S.MANUAL_REVIEW, S.EXPIRED}),
    S.PROCESSING: frozenset({S.IN_PROGRESS, S.ACTION_REQUIRED, S.MANUAL_REVIEW, S.VERIFIED, S.NOT_VERIFIED, S.FAILED}),
    S.MANUAL_REVIEW: frozenset({S.VERIFIED, S.NOT_VERIFIED, S.ACTION_REQUIRED}),
    S.FAILED: frozenset({S.PROCESSING, S.MANUAL_REVIEW, S.EXPIRED}),
    S.VERIFIED: frozenset(),
    S.NOT_VERIFIED: frozenset(),
    S.EXPIRED: frozenset(),
}
TERMINAL = frozenset({S.VERIFIED, S.NOT_VERIFIED, S.EXPIRED})
EXPIRABLE = frozenset({S.CREATED, S.IN_PROGRESS, S.ACTION_REQUIRED, S.FAILED})
UPLOADABLE = frozenset({S.CREATED, S.IN_PROGRESS, S.ACTION_REQUIRED})
EDITABLE_DECLARATION = frozenset({S.CREATED, S.IN_PROGRESS, S.ACTION_REQUIRED})


def can_transition(current: S, target: S) -> bool:
    return target in TRANSITIONS[current]
